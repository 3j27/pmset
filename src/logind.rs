use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{bail, Context, Result};

pub const DROPIN_PATH: &str = "/etc/systemd/logind.conf.d/99-pmset.conf";

#[derive(Debug, Clone)]
pub struct LogindConfig {
    pub idle_action: String,
    pub idle_action_sec: String,
    pub handle_lid_switch: String,
    pub handle_lid_switch_external_power: String,
}

impl Default for LogindConfig {
    fn default() -> Self {
        Self {
            idle_action: "ignore".to_string(),
            idle_action_sec: "30min".to_string(),
            handle_lid_switch: "suspend".to_string(),
            handle_lid_switch_external_power: "suspend".to_string(),
        }
    }
}

impl LogindConfig {
    /// Idle suspend delay in minutes. `0` means idle suspend is disabled.
    pub fn sleep_minutes(&self) -> f64 {
        if self.idle_action.eq_ignore_ascii_case("ignore") {
            return 0.0;
        }
        match parse_timespan_sec(&self.idle_action_sec) {
            Some(seconds) => seconds as f64 / 60.0,
            None => 0.0,
        }
    }

    /// Whether closing the lid performs an action (rather than being ignored).
    pub fn lidwake(&self) -> bool {
        !self.handle_lid_switch.eq_ignore_ascii_case("ignore")
            || !self
                .handle_lid_switch_external_power
                .eq_ignore_ascii_case("ignore")
    }
}

pub fn read_effective() -> LogindConfig {
    let mut values = BTreeMap::new();

    if let Some(main) = main_config_path() {
        if let Ok(text) = fs::read_to_string(main) {
            parse_into(&text, &mut values);
        }
    }

    for (_, _, path) in dropin_files() {
        if let Ok(text) = fs::read_to_string(path) {
            parse_into(&text, &mut values);
        }
    }

    let mut config = LogindConfig::default();
    if let Some(value) = values.get("IdleAction") {
        config.idle_action = value.clone();
    }
    if let Some(value) = values.get("IdleActionSec") {
        config.idle_action_sec = value.clone();
    }
    if let Some(value) = values.get("HandleLidSwitch") {
        config.handle_lid_switch = value.clone();
    }
    if let Some(value) = values.get("HandleLidSwitchExternalPower") {
        config.handle_lid_switch_external_power = value.clone();
    }
    config
}

#[derive(Debug, Default)]
pub struct Update {
    pub sleep_minutes: Option<f64>,
    pub lidwake: Option<bool>,
}

impl Update {
    pub fn is_empty(&self) -> bool {
        self.sleep_minutes.is_none() && self.lidwake.is_none()
    }
}

pub fn apply(update: &Update) -> Result<()> {
    if update.is_empty() {
        return Ok(());
    }
    if unsafe { libc::geteuid() } != 0 {
        bail!("changing sleep or lid settings requires root (try sudo)");
    }
    if update.sleep_minutes.is_some_and(|minutes| minutes > 0.0) && !suspend_supported() {
        bail!(
            "this system does not advertise suspend support in /sys/power/state; \
             use 'pmset sleep 0' to disable idle sleep"
        );
    }

    let existing = fs::read_to_string(DROPIN_PATH).unwrap_or_default();
    let text = render(update, &existing);
    write_atomic(Path::new(DROPIN_PATH), &text)?;
    reload_logind();
    Ok(())
}

fn render(update: &Update, existing: &str) -> String {
    let mut values = BTreeMap::new();
    parse_into(existing, &mut values);

    if let Some(minutes) = update.sleep_minutes {
        if minutes <= 0.0 {
            values.insert("IdleAction".to_string(), "ignore".to_string());
        } else {
            values.insert("IdleAction".to_string(), "suspend".to_string());
            let seconds = (minutes * 60.0).round() as u64;
            let span = if (minutes.fract()).abs() < f64::EPSILON {
                format!("{}min", minutes as u64)
            } else {
                format!("{seconds}s")
            };
            values.insert("IdleActionSec".to_string(), span);
        }
    }

    if let Some(lidwake) = update.lidwake {
        let action = if lidwake { "suspend" } else { "ignore" };
        values.insert("HandleLidSwitch".to_string(), action.to_string());
        values.insert(
            "HandleLidSwitchExternalPower".to_string(),
            action.to_string(),
        );
    }

    let mut text =
        String::from("# Generated by pmset. Use pmset to change these settings.\n[Login]\n");
    for (key, value) in values {
        text.push_str(&key);
        text.push('=');
        text.push_str(&value);
        text.push('\n');
    }
    text
}

fn suspend_supported() -> bool {
    fs::read_to_string("/sys/power/state")
        .map(|states| {
            states
                .split_whitespace()
                .any(|state| state == "mem" || state == "freeze")
        })
        .unwrap_or(false)
}

fn main_config_path() -> Option<&'static str> {
    [
        "/etc/systemd/logind.conf",
        "/run/systemd/logind.conf",
        "/usr/local/lib/systemd/logind.conf",
        "/usr/lib/systemd/logind.conf",
    ]
    .into_iter()
    .find(|path| Path::new(path).is_file())
}

/// Drop-in files in the order systemd reads them. Files with the same name are
/// overridden by the higher-priority directory; different names sort
/// lexicographically.
fn dropin_files() -> Vec<(String, u8, PathBuf)> {
    const DIRS: [(&str, u8); 4] = [
        ("/usr/lib/systemd/logind.conf.d", 0),
        ("/usr/local/lib/systemd/logind.conf.d", 1),
        ("/run/systemd/logind.conf.d", 2),
        ("/etc/systemd/logind.conf.d", 3),
    ];

    let mut files = Vec::new();
    for (dir, priority) in DIRS {
        let Ok(entries) = fs::read_dir(dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("conf") {
                continue;
            }
            files.push((
                entry.file_name().to_string_lossy().into_owned(),
                priority,
                path,
            ));
        }
    }
    files.sort_by(|a, b| a.0.cmp(&b.0).then(a.1.cmp(&b.1)));
    files
}

fn parse_into(text: &str, values: &mut BTreeMap<String, String>) {
    let mut in_login = false;
    for raw in text.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
            continue;
        }
        if line.starts_with('[') {
            in_login = line.eq_ignore_ascii_case("[Login]");
            continue;
        }
        if !in_login {
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            values.insert(key.trim().to_string(), value.trim().to_string());
        }
    }
}

/// Parse a systemd time span into seconds. Returns `None` for `infinity` or an
/// unparseable value.
pub fn parse_timespan_sec(value: &str) -> Option<u64> {
    let value = value.trim();
    if value.is_empty() || value.eq_ignore_ascii_case("infinity") {
        return None;
    }

    let mut total = 0.0;
    let mut rest = value;
    let mut parsed_any = false;

    while !rest.is_empty() {
        rest = rest.trim_start();
        if rest.is_empty() {
            break;
        }

        let number_end = rest
            .find(|c: char| !(c.is_ascii_digit() || c == '.'))
            .unwrap_or(rest.len());
        if number_end == 0 {
            return None;
        }
        let number: f64 = rest[..number_end].parse().ok()?;
        rest = &rest[number_end..];

        let unit_end = rest
            .find(|c: char| c.is_ascii_digit() || c == '.' || c.is_whitespace())
            .unwrap_or(rest.len());
        let unit = &rest[..unit_end];
        rest = &rest[unit_end..];

        let multiplier = match unit {
            "" | "s" | "sec" | "secs" | "second" | "seconds" => 1.0,
            "us" | "usec" | "usecs" => 1e-6,
            "ms" | "msec" | "msecs" => 1e-3,
            "m" | "min" | "mins" | "minute" | "minutes" => 60.0,
            "h" | "hr" | "hrs" | "hour" | "hours" => 3600.0,
            "d" | "day" | "days" => 86400.0,
            "w" | "week" | "weeks" => 604800.0,
            "M" | "month" | "months" => 2629800.0,
            "y" | "year" | "years" => 31557600.0,
            _ => return None,
        };
        total += number * multiplier;
        parsed_any = true;
    }

    parsed_any.then_some(total.round().max(0.0) as u64)
}

fn write_atomic(path: &Path, contents: &str) -> Result<()> {
    let parent = path
        .parent()
        .context("configuration path has no parent directory")?;
    fs::create_dir_all(parent).with_context(|| format!("failed to create {}", parent.display()))?;

    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .context("configuration path has no file name")?;
    let tmp = parent.join(format!(".{file_name}.tmp.{}", std::process::id()));

    let write_result = (|| -> Result<()> {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o644)
            .open(&tmp)
            .with_context(|| format!("failed to create {}", tmp.display()))?;
        file.write_all(contents.as_bytes())
            .with_context(|| format!("failed to write {}", tmp.display()))?;
        file.sync_all()
            .with_context(|| format!("failed to sync {}", tmp.display()))?;
        fs::rename(&tmp, path).with_context(|| format!("failed to replace {}", path.display()))?;
        Ok(())
    })();

    if write_result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    write_result
}

fn reload_logind() {
    match Command::new("systemctl")
        .args(["reload", "systemd-logind"])
        .status()
    {
        Ok(status) if status.success() => {}
        Ok(status) => eprintln!(
            "pmset: warning: systemd-logind reload exited with {status}; settings will apply after its next reload"
        ),
        Err(err) => eprintln!(
            "pmset: warning: could not reload systemd-logind ({err}); settings will apply after its next reload"
        ),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_time_spans() {
        assert_eq!(parse_timespan_sec("30min"), Some(1800));
        assert_eq!(parse_timespan_sec("1h"), Some(3600));
        assert_eq!(parse_timespan_sec("90s"), Some(90));
        assert_eq!(parse_timespan_sec("1h 30min"), Some(5400));
        assert_eq!(parse_timespan_sec("1.5min"), Some(90));
        assert_eq!(parse_timespan_sec("0"), Some(0));
        assert_eq!(parse_timespan_sec("infinity"), None);
        assert_eq!(parse_timespan_sec("nonsense"), None);
    }

    #[test]
    fn parses_login_section_only() {
        let text = r#"
[Other]
IdleAction=poweroff
[Login]
IdleAction=suspend
IdleActionSec=10min
HandleLidSwitch=ignore
"#;
        let mut values = BTreeMap::new();
        parse_into(text, &mut values);
        assert_eq!(values.get("IdleAction").unwrap(), "suspend");
        assert_eq!(values.get("IdleActionSec").unwrap(), "10min");
        assert_eq!(values.get("HandleLidSwitch").unwrap(), "ignore");
    }

    #[test]
    fn reports_sleep_and_lid_state() {
        let config = LogindConfig {
            idle_action: "suspend".into(),
            idle_action_sec: "15min".into(),
            handle_lid_switch: "ignore".into(),
            handle_lid_switch_external_power: "ignore".into(),
        };
        assert_eq!(config.sleep_minutes(), 15.0);
        assert!(!config.lidwake());

        let config = LogindConfig {
            idle_action: "ignore".into(),
            ..Default::default()
        };
        assert_eq!(config.sleep_minutes(), 0.0);
        assert!(config.lidwake());
    }

    #[test]
    fn renders_sleep_and_lid_settings_and_keeps_other_keys() {
        let existing = "[Login]\nCustomKey=keep-me\nIdleAction=ignore\n";
        let update = Update {
            sleep_minutes: Some(30.0),
            lidwake: Some(false),
        };
        let text = render(&update, existing);
        assert!(text.contains("CustomKey=keep-me"));
        assert!(text.contains("IdleAction=suspend"));
        assert!(text.contains("IdleActionSec=30min"));
        assert!(text.contains("HandleLidSwitch=ignore"));
        assert!(text.contains("HandleLidSwitchExternalPower=ignore"));
        assert!(!text.contains("IdleAction=ignore"));
    }

    #[test]
    fn renders_fractional_minutes_as_seconds() {
        let update = Update {
            sleep_minutes: Some(2.5),
            lidwake: None,
        };
        let text = render(&update, "");
        assert!(text.contains("IdleActionSec=150s"));
    }

    #[test]
    fn disabling_sleep_leaves_an_ignore_action() {
        let update = Update {
            sleep_minutes: Some(0.0),
            lidwake: None,
        };
        let text = render(&update, "");
        assert!(text.contains("IdleAction=ignore"));
        assert!(!text.contains("IdleAction=suspend"));
    }

    #[test]
    fn writes_files_atomically() {
        let directory = std::env::temp_dir().join(format!(
            "pmset-logind-test-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let path = directory.join("99-pmset.conf");
        write_atomic(&path, "hello\n").unwrap();
        assert_eq!(fs::read_to_string(&path).unwrap(), "hello\n");
        let _ = fs::remove_dir_all(&directory);
    }
}
